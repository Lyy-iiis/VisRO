def _rodrigues(axis, theta):
    k = np.asarray(axis, float)
    k = k / np.linalg.norm(k)
    K = np.array([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
    return np.eye(3) + math.sin(theta) * K + (1 - math.cos(theta)) * K @ K


def physical_fold(cells):
    """face index -> (outward normal, glyph up) as integer 3-tuples."""
    cells = [tuple(int(v) for v in c) for c in cells]
    if len(cells) != 6 or len(set(cells)) != 6:
        raise ValueError("a cube net has six distinct cells")
    where = {c: i for i, c in enumerate(cells)}
    corners = [np.array([[c, -r, 0], [c + 1, -r, 0], [c + 1, -r - 1, 0], [c, -r - 1, 0]], float)
               for r, c in cells]
    normal = [np.array([0.0, 0.0, 1.0]) for _ in cells]
    up = [np.array([0.0, 1.0, 0.0]) for _ in cells]
    parent, order, todo = {0: None}, [0], deque([0])
    while todo:
        i = todo.popleft()
        r, c = cells[i]
        for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            j = where.get((r + dr, c + dc))
            if j is not None and j not in parent:
                parent[j] = i
                order.append(j)
                todo.append(j)
    if len(parent) != 6:
        raise ValueError("net is not edge-connected")
    children = {i: [j for j, p in parent.items() if p == i] for i in range(6)}

    def subtree(j):
        out, stack = [], [j]
        while stack:
            k = stack.pop()
            out.append(k)
            stack.extend(children[k])
        return out

    for j in order[1:]:
        p = parent[j]
        shared = [a for a in corners[p] if any(np.allclose(a, b, atol=1e-6) for b in corners[j])]
        if len(shared) != 2:
            raise ValueError("hinge not found")
        h0, h1 = shared
        mid = (h0 + h1) / 2
        rot = None
        for sgn in (1, -1):
            R = _rodrigues(h1 - h0, sgn * math.pi / 2)
            centre = R @ (corners[j].mean(0) - h0) + h0
            if np.dot(centre - mid, normal[p]) < -0.25:   # behind the parent's drawn side
                rot = R
        if rot is None:
            raise ValueError("no fold direction")
        for k in subtree(j):
            corners[k] = (rot @ (corners[k] - h0).T).T + h0
            normal[k] = rot @ normal[k]
            up[k] = rot @ up[k]
    centres = np.array([c.mean(0) for c in corners])
    mid = centres.mean(0)
    frames = {}
    for i in range(6):
        out = np.rint((centres[i] - mid) * 2).astype(int)
        n = np.rint(normal[i]).astype(int)
        if not np.array_equal(out, n):
            raise ValueError(f"face {i}: drawn side does not face outward")
        frames[i] = (tuple(int(v) for v in n), tuple(int(v) for v in np.rint(up[i])))
    if len({f[0] for f in frames.values()}) != 6:
        raise ValueError("faces overlap: not a cube net")
    return frames


@lru_cache(maxsize=1)
def rotations():
    gens = [np.array([[1, 0, 0], [0, 0, -1], [0, 1, 0]]), np.array([[0, 0, 1], [0, 1, 0], [-1, 0, 0]])]
    seen = {tuple(np.eye(3, dtype=int).ravel())}
    frontier = [np.eye(3, dtype=int)]
    while frontier:
        nxt = []
        for M in frontier:
            for G in gens:
                P = G @ M
                if tuple(P.ravel()) not in seen:
                    seen.add(tuple(P.ravel()))
                    nxt.append(P)
        frontier = nxt
    mats = [np.array(k).reshape(3, 3) for k in sorted(seen)]
    assert len(mats) == 24 and all(round(np.linalg.det(m)) == 1 for m in mats)
    return mats


def shown_up(slot, step):
    n, u = np.array(SLOT_N[slot]), np.array(SLOT_REF[slot])
    for _ in range(int(step) % 4):
        u = np.cross(n, u)
    return tuple(int(v) for v in u)


def matches(frames, view, oriented):
    """view: {slot: (face, step)} -> True iff some rotation shows exactly this."""
    for M in rotations():
        ok = True
        for slot, (fid, step) in view.items():
            n, u = frames[fid]
            if tuple(M @ np.array(n)) != SLOT_N[slot] or (
                    oriented and tuple(M @ np.array(u)) != shown_up(slot, step)):
                ok = False
                break
        if ok:
            return True
    return False


def legal_steps(frames, faces):
    """{slot: face} -> {slot: step} of the one legal view showing these faces there, or None.

    Three mutually adjacent faces fix the rotation, so a legal face arrangement has
    exactly one legal orientation of its symbols."""
    for M in rotations():
        if all(tuple(M @ np.array(frames[f][0])) == SLOT_N[s] for s, f in faces.items()):
            out = {}
            for s, f in faces.items():
                up = tuple(int(v) for v in M @ np.array(frames[f][1]))
                out[s] = next(k for k in range(4) if shown_up(s, k) == up)
            return out
    return None


