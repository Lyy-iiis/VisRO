"""Independent verifier for cube_unfold (does not import generator).

What it recomputes, and from what
---------------------------------
1. A PHYSICAL fold of meta.net_cells: every net square is a unit square in the
   z=0 plane (cell (r, c) -> x in [c, c+1], y in [-r-1, -r], drawn side +Z,
   glyph up +Y); each child square (with its whole subtree) is rotated 90 deg
   about the hinge it shares with its parent, towards the parent's back, and
   at the end every face's drawn side must point away from the cube centre.
   meta.folded_faces is only compared against this, never used.
2. The 24 proper rotations, generated by closure of two quarter turns.
3. Each candidate view {slot: [face, step]} is drawn with outward normals
   top +Z, right +Y, left +X; the glyph up is the slot reference (top +Y,
   sides +Z) turned `step` right-hand quarter turns about the normal.  A
   candidate matches iff one rotation carries the folded cube's three faces
   (and, for glyph tiers, their up vectors) onto the shown ones.
4. The IMAGE is decoded on its own: every net cell and every candidate face
   is unwarped through the documented isometric projection (positions from
   meta.geometry; the camera constants are recomputed from cube_size and must
   equal the meta, so a mirrored camera cannot be declared), its colour and
   white-glyph mask are read, each candidate face is identified (by colour,
   and/or by matching the glyph against the six net-cell glyphs read from the
   same image in 4 rotations), every candidate symbol must be drawn like its
   net symbol, and the answer is recomputed from those decoded views alone.
   The printed number under every cube is matched against all candidate
   numbers rendered with the declared font.
5. Tier rules stated in TIER_DEFINITIONS: candidate count, number of matching
   cubes, and on rotation-only tiers that every negative is a legal view with
   exactly one symbol turned.

Uniqueness: the legal views are exactly the rotation orbit, so every
candidate's status is a function of (net, view); the verifier proves that the
image fixes (net, view) with margin -- face colours pairwise CIEDE2000 >= 25,
glyph identity/orientation decoded with an IoU margin, and every alternative
glyph reading would change a connected patch of >= MIN_TURN_PX pixels at the
delivered size -- and that the question states the conventions it needs.
"""
