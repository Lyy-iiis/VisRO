def _close(a, b, tol=COLOR_TOL):
    return a is not None and b is not None and max(abs(int(x) - int(y)) for x, y in zip(a, b)) <= tol


def decode_views(cells, geo, arr, *, oriented, mono):
    """Read the page: (net colours, [{slot: (face, step)} or None per cube], problems).

    Uses only the net cell layout and the drawing geometry -- never the meta
    views, colours or answer -- so the answer recomputed from its output is an
    image-only answer.  Problems flag overpaint, undecidable or illegible faces.
    """
    problems: list[str] = []
    iso = geo["iso"]
    if min(iso["a"], iso["b"], iso["c"], geo["net"]["cell_px"]) <= 0:
        # a negative scale would read every face mirrored; never decode through it
        return {}, None, ["meta.geometry: non-positive projection scale (mirrored or degenerate camera)"]
    inner = _inner(geo)

    # ---------------------------------------------------------------- image: net cells
    net_col, net_mask = {}, {}
    for fid, cell in enumerate(cells):
        col, mask, tamper = _read(_net_patch(arr, geo, cell), inner)
        net_col[fid], net_mask[fid] = col, mask
        problems += _tampered(f"net face {fid}", tamper)
        if mask.sum() < MIN_SYMBOL_SHARE * inner.sum():
            problems.append(f"net face {fid}: no visible symbol")
    if problems:
        return net_col, None, problems
    if oriented:
        # no glyph is rotationally symmetric or a rotation of another glyph (as decoded)
        for f in range(6):
            for g2 in range(6):
                for k in range(4):
                    if (f, k) != (g2, 0) and _iou(net_mask[g2], np.rot90(net_mask[f], k)) > 1 - MIN_IOU_MARGIN:
                        problems.append(f"net glyph {g2} indistinguishable from glyph {f} turned {k}")
    else:
        for f in range(6):
            if _iou(net_mask[f], np.rot90(net_mask[f], 1)) < 0.8:
                problems.append(f"net face {f}: dot symbol is not rotation-invariant as drawn")

    # ---------------------------------------------------------------- image: candidate faces
    decoded = []
    for i in range(len(geo["cubes"])):
        view = {}
        for slot in SLOTS:
            col, mask, tamper = _read(_cube_patch(arr, geo, i, slot), inner)
            where = f"cube {i + 1} {slot}"
            problems += _tampered(where, tamper)
            same = [f for f in range(6) if _close(col, net_col[f])]
            if mono:
                if len(same) != 6:
                    problems.append(f"{where}: colour {col} is not the shared face colour")
                pool = list(range(6))
            else:
                if len(same) != 1:
                    problems.append(f"{where}: colour {col} matches net faces {same}")
                    continue
                pool = same
            if mask.sum() < MIN_SYMBOL_SHARE * inner.sum():
                problems.append(f"{where}: no visible symbol")
                continue
            if not oriented:
                # the dot must be there and drawn like the net's (a dot-less face is no net face)
                iou = _iou(mask, net_mask[same[0]])
                if iou < MIN_DOT_IOU:
                    problems.append(f"{where}: dot differs from the net's (IoU {iou:.2f} < {MIN_DOT_IOU})")
                view[slot] = (same[0], 0)
                continue
            scores = sorted(((_iou(mask, np.rot90(net_mask[f], k)), f, k) for f in range(6) for k in range(4)),
                            reverse=True)
            ranked = [s for s in scores if s[1] in pool]     # readings a viewer could confuse
            best, second = ranked[0], ranked[1]
            if best[0] < MIN_IOU or best[0] - second[0] < MIN_IOU_MARGIN:
                problems.append(f"{where}: glyph reading not decisive (IoU {best[0]:.2f}, next {second[0]:.2f})")
            if best != scores[0]:
                problems.append(f"{where}: glyph looks more like face {scores[0][1]} than its colour's face")
            f, k = best[1], best[2]
            shown_mask = np.rot90(net_mask[f], k)
            # the whole glyph is drawn like the net's (no part missing, nothing added)
            ratio = mask.sum() / max(int(shown_mask.sum()), 1)
            if best[0] < MIN_CAND_IOU or not CAND_AREA[0] <= ratio <= CAND_AREA[1]:
                problems.append(f"{where}: glyph not drawn like the net's (IoU {best[0]:.2f}, "
                                f"area ratio {ratio:.2f})")
            # legibility at the delivered size: every other reading of this face changes a visible patch
            px_per_cell = _face_area_px(geo, slot) / (GRID * GRID)
            alts = [(f, kk) for kk in range(4) if kk != k] + ([(g2, kk) for g2 in range(6) if g2 != f
                                                             for kk in range(4)] if mono else [])
            worst = min(_largest_patch(shown_mask, np.rot90(net_mask[a], b)) for a, b in alts) * px_per_cell
            if worst < MIN_TURN_PX:
                problems.append(f"{where}: another glyph reading changes only {worst:.0f} px (< {MIN_TURN_PX})")
            view[slot] = (f, k)
        decoded.append(view if len(view) == 3 else None)
    return net_col, decoded, problems


def verify(record, image):  # noqa: C901 - one linear checklist
    problems: list[str] = []
    m = record.get("meta") or {}
    tier = record.get("tier")
    spec = TIER_SPEC.get(tier)
    if spec is None:
        return [f"unknown tier {tier!r}"]

    # ---------------------------------------------------------------- form
    if record.get("question") != QUESTION:
        problems.append("question text differs from the declared form")
    if record.get("answer_type") != "token-list":
        problems.append(f"answer_type {record.get('answer_type')!r} != 'token-list'")
    ans = record.get("answer", "")
    if not re.fullmatch(r"[1-9][0-9]*(,[1-9][0-9]*)*", ans or ""):
        return problems + [f"answer {ans!r} is not a comma-separated list of numbers"]
    gold = [int(x) for x in ans.split(",")]
    cands = m.get("candidates") or []
    n = len(cands)
    if gold != sorted(set(gold)):
        problems.append("answer not strictly increasing")
    if not spec["n"][0] <= n <= spec["n"][1] or m.get("n_candidates") != n:
        problems.append(f"{n} candidates outside tier range {spec['n']}")
    if [c.get("index") for c in cands] != list(range(1, n + 1)):
        problems.append("candidate indices are not 1..n in order")
    if gold and (gold[0] < 1 or gold[-1] > n or len(gold) >= n):
        problems.append("answer must name >= 1 and < all candidates, within 1..n")
    # the question carries no format example: no number that could be (part of) a real answer
    if re.search(r"[0-9]", record.get("question") or ""):
        problems.append("question contains a number (format examples are not allowed)")
    oriented = bool(m.get("oriented"))
    for key, want in (("oriented", spec["oriented"]), ("rotation_only", spec["rotation_only"]),
                      ("monochrome", spec["mono"])):
        if bool(m.get(key)) != want:
            problems.append(f"meta.{key}={m.get(key)!r} but tier {tier} requires {want}")
    size = spec["size"]
    if image.size != (size, size) or m.get("resolution") != size:
        problems.append(f"image {image.size} / meta resolution {m.get('resolution')} != tier size {size}")
    if problems:
        return problems

    # ---------------------------------------------------------------- symbols (perceptual distinctness)
    colours = [tuple(int(v) for v in c) for c in m["face_colors"]]
    glyphs = list(m["face_glyphs"])
    if len(colours) != 6 or len(glyphs) != 6:
        return ["need six face colours and six glyphs"]
    if spec["mono"]:
        if len(set(colours)) != 1:
            problems.append("monochrome tier with differing face colours")
    else:
        worst = min((de2000(a, b), i, j) for i, a in enumerate(colours) for j, b in enumerate(colours) if i < j)
        if worst[0] < MIN_DE00:
            problems.append(f"faces {worst[1]},{worst[2]} colours only dE00={worst[0]:.1f} apart (< {MIN_DE00})")
    for c in set(colours):
        if white_contrast(c) < MIN_GLYPH_CONTRAST:
            problems.append(f"white symbol on {c} has contrast {white_contrast(c):.2f} < {MIN_GLYPH_CONTRAST}")
    if oriented:
        if set(glyphs) != GLYPHS:
            problems.append(f"glyph tier needs the six distinct glyphs, got {glyphs}")
    elif set(glyphs) != {"dot"}:
        problems.append("dot tier with non-dot symbols")

    # ---------------------------------------------------------------- logic: independent fold + orbit
    cells = [tuple(c) for c in m["net_cells"]]
    try:
        frames = physical_fold(cells)
    except ValueError as exc:
        return problems + [f"net does not fold: {exc}"]
    for fid, (nrm, up) in frames.items():
        ff = (m.get("folded_faces") or {}).get(str(fid)) or {}
        if tuple(ff.get("normal", ())) != nrm or tuple(ff.get("up", ())) != up:
            problems.append(f"meta.folded_faces[{fid}] disagrees with the physical fold")
            break
    views = []
    for c in cands:
        v = c.get("view") or {}
        try:
            view = {s: (int(v[s][0]), int(v[s][1])) for s in SLOTS}
        except (KeyError, TypeError, ValueError, IndexError):
            return problems + [f"candidate {c.get('index')}: malformed view"]
        if len({f for f, _ in view.values()}) != 3 or not all(0 <= f < 6 and 0 <= st < 4 for f, st in view.values()):
            problems.append(f"candidate {c['index']}: view must show three distinct faces with steps 0..3")
            return problems
        if not oriented and any(st for _, st in view.values()):
            problems.append(f"candidate {c['index']}: dot tier view with a non-zero step")
        views.append(view)
    shown = [tuple(view[s] if oriented else view[s][0] for s in SLOTS) for view in views]
    if len(set(shown)) != len(shown):
        problems.append("two candidates show the same view")
    valid = [matches(frames, view, oriented) for view in views]
    want = [i + 1 for i, ok in enumerate(valid) if ok]
    if want != gold:
        problems.append(f"answer {ans} but the physical fold gives {','.join(map(str, want)) or '(none)'}")
    if list(m.get("consistent_idx") or []) != want or [bool(c.get("consistent")) for c in cands] != valid:
        problems.append("meta consistent flags disagree with the physical fold")
    if not want or len(want) == n:
        problems.append("need at least one matching and one non-matching cube")
    lo, hi = spec["match"]
    if not lo <= len(want) <= hi:
        problems.append(f"{len(want)} matching cubes outside tier range {lo}-{hi}")
    if spec["rotation_only"]:
        for i, view in enumerate(views):
            if valid[i]:
                continue
            legal = legal_steps(frames, {s: view[s][0] for s in SLOTS})
            if legal is None:
                problems.append(f"candidate {i + 1}: rotation-only tier negative has a wrong face arrangement")
                break
            turned = sum(view[s][1] != legal[s] for s in SLOTS)
            if turned != 1:
                problems.append(f"candidate {i + 1}: rotation-only tier negative turns {turned} symbols, not 1")
                break

    # ---------------------------------------------------------------- image: layout sanity
    geo = m.get("geometry") or {}
    try:
        cs = int(geo["cube_size"])
        net = geo["net"]
        boxes = [(int(x), int(y), int(x) + cs, int(y) + cs) for x, y in geo["cubes"]]
        nb = (net["x0"], net["y0"],
              net["x0"] + (max(c for _, c in cells) - net["c_min"] + 1) * net["cell_px"],
              net["y0"] + (max(r for r, _ in cells) - net["r_min"] + 1) * net["cell_px"])
        assert len(boxes) == n and len(geo["labels"]) == n
    except (KeyError, TypeError, ValueError, AssertionError):
        return problems + ["meta.geometry missing or malformed"]
    problems += geometry_problems(geo, cells, size)
    for b in boxes + [nb]:
        if b[0] < 0 or b[1] < 0 or b[2] > size or b[3] > size:
            problems.append(f"box {b} leaves the image")
    for i, a in enumerate(boxes + [nb]):
        for b in (boxes + [nb])[i + 1:]:
            if a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]:
                problems.append(f"boxes {a} and {b} overlap")
    if problems:
        return problems

    arr = np.asarray(image.convert("RGB"), dtype=float)
    net_col, decoded, probs = decode_views(cells, geo, arr, oriented=oriented, mono=spec["mono"])
    problems += probs
    for fid in range(6):
        if net_col.get(fid) is not None and not _close(net_col[fid], colours[fid]):
            problems.append(f"net face {fid}: image colour {net_col[fid]} != meta {colours[fid]}")
    if decoded is None:
        return problems
    for i, view in enumerate(decoded):
        mv = {s: tuple(cands[i]["view"][s]) for s in SLOTS}
        if view is not None and view != mv:
            problems.append(f"cube {i + 1}: image shows {view} but meta says {mv}")
    if all(v is not None for v in decoded):
        from_pixels = [i + 1 for i, v in enumerate(decoded) if matches(frames, v, oriented)]
        if from_pixels != gold:
            problems.append(f"answer from decoded image {from_pixels} != {gold}")
        seen = [tuple(v[s] if oriented else v[s][0] for s in SLOTS) for v in decoded]
        if len(set(seen)) != len(seen):
            problems.append("two cubes look identical in the image")

    # ---------------------------------------------------------------- image: printed numbers
    px = int(geo["label_px"])
    draw = ImageDraw.Draw(Image.new("L", (1, 1)))
    texts = [str(j + 1) for j in range(n)]
    widths = {t: draw.textbbox((0, 0), t, font=_font(px))[2] - draw.textbbox((0, 0), t, font=_font(px))[0]
              for t in texts}
    dark = arr.min(axis=2) < 128
    for i in range(n):
        _, y = geo["labels"][i]                     # numbers are centred under their cube
        bx0, by0 = int(boxes[i][0]), int(y) - 2
        box = (bx0, by0, min(size, bx0 + cs), min(size, by0 + px + 8))
        ink = dark[box[1]:box[3], box[0]:box[2]]
        centre = boxes[i][0] + cs / 2
        scores = sorted(((_iou(ink, _text_mask(t, px, (centre - widths[t] / 2, y), box)), t) for t in texts),
                        reverse=True)
        if scores[0][1] != texts[i] or scores[0][0] - scores[1][0] < MIN_LABEL_MARGIN:
            problems.append(f"number under cube {i + 1} reads as {scores[0][1]!r} "
                            f"(IoU {scores[0][0]:.2f} vs {scores[1][0]:.2f})")
    return problems
