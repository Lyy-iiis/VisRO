GRID = 40
_g = (np.arange(GRID) + 0.5) / GRID
UU, VV = np.meshgrid(_g, _g)           # UU: face-local right 0..1, VV: face-local down 0..1
EDGE_PX = 3.0                          # sample no closer than this to a drawn face edge (outline + blur)
WHITE = np.array([255.0, 255.0, 255.0])


def _bilinear(arr, xs, ys):
    h, w = arr.shape[:2]
    xs = np.clip(xs, 0, w - 1.001)
    ys = np.clip(ys, 0, h - 1.001)
    x0, y0 = np.floor(xs).astype(int), np.floor(ys).astype(int)
    fx, fy = (xs - x0)[..., None], (ys - y0)[..., None]
    return (arr[y0, x0] * (1 - fx) * (1 - fy) + arr[y0, x0 + 1] * fx * (1 - fy)
            + arr[y0 + 1, x0] * (1 - fx) * fy + arr[y0 + 1, x0 + 1] * fx * fy)


def _net_patch(arr, geo, cell):
    net = geo["net"]
    r, c = cell
    x0 = net["x0"] + (c - net["c_min"]) * net["cell_px"]
    y0 = net["y0"] + (r - net["r_min"]) * net["cell_px"]
    return _bilinear(arr, x0 + UU * net["cell_px"] - 0.5, y0 + VV * net["cell_px"] - 0.5)


def _project(geo, i, P):
    left, top = geo["cubes"][i]
    iso = geo["iso"]
    X, Y, Z = P[..., 0], P[..., 1], P[..., 2]
    return (left + iso["ox"] + (Y - X) * iso["a"], top + iso["oy"] + (X + Y) * iso["b"] - Z * iso["c"])


def _cube_patch(arr, geo, i, slot):
    """Face `slot` of cube i, resampled in its reference frame (step 0 = upright)."""
    n, u = np.array(SLOT_N[slot], float), np.array(SLOT_REF[slot], float)
    right = np.cross(u, n)
    centre = (np.ones(3) + n) / 2
    P = centre + (UU[..., None] - 0.5) * right + (0.5 - VV[..., None]) * u
    sx, sy = _project(geo, i, P)
    return _bilinear(arr, sx - 0.5, sy - 0.5)


def _inner(geo):
    """Face-local window at least EDGE_PX image pixels from every edge, for net and cube faces alike."""
    iso = geo["iso"]
    a, b, c = iso["a"], iso["b"], iso["c"]
    per_unit = min(geo["net"]["cell_px"], 2 * a * b / math.hypot(a, b), a * c / math.hypot(a, b))
    half = 0.5 - max(0.06, EDGE_PX / per_unit)
    return (np.abs(UU - 0.5) < half) & (np.abs(VV - 0.5) < half)


def documented_camera(cube_size):
    """The page's isometric camera, recomputed from the cube box size (see page_geometry).

    pad = int(0.16 cs); a = (cs - 2 pad) / 2; b = a / 2; c = 1.04 a; origin (cs/2, 0.62 cs).
    With a, b, c > 0 a point (x, y, z) is drawn at screen-right (y - x) a, so the camera
    sits at (+,+,+) looking at the cube from above and the view is not mirrored."""
    cs = int(cube_size)
    a = (cs - 2 * int(cs * 0.16)) / 2
    return {"a": a, "b": a / 2, "c": 1.04 * a, "ox": cs / 2, "oy": 0.62 * cs}


def geometry_problems(geo, cells, size):
    """The drawing geometry the decode trusts must be the documented, unmirrored one."""
    probs = []
    try:
        want = documented_camera(geo["cube_size"])
        iso = geo["iso"]
        bad = [k for k, v in want.items()
               if not isinstance(iso.get(k), (int, float)) or abs(float(iso[k]) - v) > 1e-6]
        if bad or int(geo["cube_size"]) <= 0:
            probs.append(f"meta.geometry.iso {bad} is not the documented right-handed camera")
        net = geo["net"]
        if not (isinstance(net["cell_px"], int) and net["cell_px"] > 0):
            probs.append(f"meta.geometry.net.cell_px {net['cell_px']!r} must be a positive integer")
        if (net["r_min"], net["c_min"]) != (min(r for r, _ in cells), min(c for _, c in cells)):
            probs.append("meta.geometry.net origin cell is not the net's top-left")
        if geo.get("size") != size:
            probs.append(f"meta.geometry.size {geo.get('size')} != {size}")
    except (KeyError, TypeError, ValueError):
        probs.append("meta.geometry missing or malformed")
    return probs


def _face_area_px(geo, slot):
    """Projected area of one unit face of a candidate cube, in image pixels."""
    iso = geo["iso"]
    return 2 * iso["a"] * iso["b"] if slot == "top" else iso["a"] * iso["c"]


def _read(patch, inner):
    """(flat face colour or None, glyph mask, tamper score) inside the window `inner`.

    tamper score = (share of pixels off the face-colour..white line,
                    grid cells of a blend region too thick to be anti-aliasing)."""
    px = patch[inner].reshape(-1, 3)
    dark = px.min(1) < 235
    counts = Counter(map(tuple, np.rint(px[dark]).astype(int)))
    if not counts:
        return None, np.zeros_like(inner), (1.0, 0)
    colour = np.array(counts.most_common(1)[0][0], float)
    seg = WHITE - colour
    t = np.clip(((patch - colour) @ seg) / max(float(seg @ seg), 1.0), 0, 1)
    off = np.linalg.norm(patch - (colour + t[..., None] * seg), axis=2)
    mask = (t > 0.5) & inner
    foreign = float(((off > 30) & inner).sum() / inner.sum())
    blend = (t > 0.15) & (t < 0.85) & inner
    flat = int(ndimage.binary_erosion(blend, structure=np.ones((3, 3)), iterations=2).sum())
    return tuple(int(v) for v in colour), mask, (foreign, flat)


def _tampered(where, score):
    foreign, flat = score
    if foreign > MAX_FOREIGN:
        return [f"{where}: {foreign:.1%} pixels are neither face colour nor symbol (overpainted?)"]
    if flat > MAX_FLAT_BLEND:
        return [f"{where}: {flat} cells of flat intermediate colour (overpainted?)"]
    return []


def _iou(a, b):
    u = np.logical_or(a, b).sum()
    return float(np.logical_and(a, b).sum() / u) if u else 0.0


def _largest_patch(a, b):
    lab, n = ndimage.label(np.logical_xor(a, b), structure=np.ones((3, 3)))
    return int(np.bincount(lab.ravel())[1:].max()) if n else 0


@lru_cache(maxsize=4)
def _font(px):
    return ImageFont.truetype(str(ROOT / "assets" / "fonts" / "DejaVuSans-Bold.ttf"), size=px)


def _text_mask(text, px, origin, box):
    """Mask of `text` drawn with its origin at `origin`, cropped to `box`."""
    x0, y0, x1, y1 = box
    im = Image.new("L", (x1 - x0, y1 - y0), 0)
    ImageDraw.Draw(im).text((origin[0] - x0, origin[1] - y0), text, fill=255, font=_font(px))
    return np.asarray(im) >= 128


